const assert = require('node:assert/strict')
const { load } = require('./test-ts-loader.cjs')
const { autoTagPrompt } = load('src/lib/promptAutoTags.ts')
const { buildPromptCompletionRequest } = load('electron/promptCompletion.ts')

assert.equal(autoTagPrompt('A runner crosses the street.'), '##scene\nA runner crosses the street.')
assert.equal(autoTagPrompt('Scene: A runner crosses the street.\nSound: Rain on pavement.\nMusic: Sparse strings.'), '##scene\nA runner crosses the street.\n\n##soundscape\nRain on pavement.\n\n##music\nSparse strings.')
assert.equal(autoTagPrompt('##scene\nKeep this custom layout.'), '##scene\nKeep this custom layout.', 'existing sections are preserved')
assert.equal(autoTagPrompt(''), '', 'empty prompt is unchanged')
const lm = buildPromptCompletionRequest('lmstudio', 'local-model', 'A camera follows a dancer.')
assert.equal(lm.path, '/chat/completions')
assert.equal(lm.body.max_tokens, 72)
assert.equal(lm.body.reasoning_effort, 'none')
assert.equal(lm.body.messages[0].role, 'user')
const ollama = buildPromptCompletionRequest('ollama', 'local-model', 'A camera follows a dancer.')
assert.equal(ollama.path, '/api/generate')
assert.equal(ollama.body.options.num_predict, 72)
process.stdout.write('PASS: prompt auto tagging and compact Ollama/LM Studio suggestion requests\n')
