const assert = require('node:assert/strict')
const { load } = require('./test-ts-loader.cjs')
const { buildLtxRippleWorkflow, rippleFrameOptions, rippleFramesForSeconds, rippleSize, LTX_RIPPLE_DEFAULT_PROMPT } = load('src/lib/ltxRippleWorkflow.ts')
const { resolveFrameSize } = load('src/lib/frameResolution.ts')
const { planRippleChunks } = load('src/lib/ltxRippleBatch.ts')
const { extractOutputFile, extractOutputUrl } = load('src/lib/workflow.ts')

const models = { diffusion: 'ltx-distilled.safetensors', textEncoder: 'gemma.safetensors', videoVae: 'video.safetensors', audioVae: 'audio.safetensors', latentUpscaler: '' }
const options = { prompt: '', negativePrompt: '', width: 768, height: 512, frames: 97, strength: 1.35, seed: 42, filenamePrefix: 'LTX_Ripple/FFAF' }
const graph = buildLtxRippleWorkflow(options, models, 'LTX/LTX25_Ripple_v11.safetensors', { name: 'source.mp4' }, { name: 'edit.png' })
assert.deepEqual(Array.from(rippleFrameOptions(96)), [49, 57, 65, 73, 81, 89, 97])
assert.equal(rippleFramesForSeconds(5), 121)
assert.equal(rippleFramesForSeconds(10), 241)
assert.equal(rippleFramesForSeconds(20), 481)
assert.equal(rippleFrameOptions(120).at(-1), 121, 'An edited opening frame plus 120 source frames makes a five-second guide')
const chunks = planRippleChunks(60, 10, 1)
assert.equal(chunks.length, 7)
assert.equal(chunks[0].sourceFrames, 240)
assert.equal(chunks[1].startFrame, 216)
assert.equal(chunks[1].overlapFrames, 24)
assert.ok(chunks.at(-1).startFrame + chunks.at(-1).sourceFrames >= 60 * 24)
assert.throws(() => planRippleChunks(301, 10, 1), /5 minutes/)
const shortTail = planRippleChunks(11, 10, 2)
assert.equal(shortTail.at(-1).sourceFrames, 104, 'A short final chunk stays longer than twice its overlap')
for (const chunkLength of [5, 10, 15]) for (const overlap of [0, 1 / 3, 2 / 3, 1, 2]) for (const duration of [5.1, 10.1, 11, 15.1, 20.1, 60.1, 299.9]) {
  const planned = planRippleChunks(duration, chunkLength, overlap)
  assert.ok(planned.at(-1).startFrame + planned.at(-1).sourceFrames >= Math.ceil(Math.round(duration * 24) / 8) * 8)
  assert.ok(planned.every(chunk => chunk.index === 0 || chunk.overlapFrames < chunk.sourceFrames / 2), `Assembler accepts ${duration}s with ${chunkLength}s chunks and ${overlap}s overlap`)
}
assert.equal(JSON.stringify(rippleSize(1920, 1080)), JSON.stringify({ width: 768, height: 448 }))
assert.equal(JSON.stringify(resolveFrameSize({ width: 1920, height: 1080 }, { mode: 'source', width: 768, height: 512 })), JSON.stringify({ width: 1920, height: 1088 }))
assert.equal(JSON.stringify(resolveFrameSize({ width: 1920, height: 1080 }, { mode: 'detailed', width: 768, height: 512 })), JSON.stringify({ width: 1024, height: 576 }))
assert.equal(resolveFrameSize({ width: 1920, height: 1080 }, { mode: 'custom', width: 1024, height: 575 }), null)
assert.equal(graph['6'].inputs.text, LTX_RIPPLE_DEFAULT_PROMPT)
assert.equal(graph['5'].inputs.strength_model, 1.35)
assert.deepEqual(Array.from(graph['14'].inputs.image1), ['13', 0], 'Replacement frame precedes source frames')
assert.deepEqual(Array.from(graph['14'].inputs.image2), ['12', 0])
assert.equal(graph['15'].inputs.length, 97, 'Guide batch is capped to output length')
assert.equal(graph['17'].inputs.frame_idx, 0, 'Guide starts inside generated video at first frame')
assert.equal(graph['17'].inputs.strength, 1, 'Motion guide defaults to full strength')
assert.equal(buildLtxRippleWorkflow({ ...options, guideStrength: 0.7 }, models, 'ripple.safetensors', { name: 'source.mp4' }, { name: 'edit.png' })['17'].inputs.strength, 0.7)
assert.deepEqual(Array.from(graph['17'].inputs.image), ['15', 0])
assert.deepEqual(Array.from(graph['19'].inputs.video_latent), ['17', 2])
assert.deepEqual(Array.from(graph['27'].inputs.samples), ['26', 2], 'Decode after cropping guide tokens')
assert.deepEqual(Array.from(graph['28'].inputs.audio), ['10', 1], 'Carry original audio')
assert.equal(graph['29'].inputs['format.codec'], 'auto')
assert.equal(buildLtxRippleWorkflow({ ...options, frames: 241 }, models, 'ripple.safetensors', { name: 'source.mp4' }, { name: 'edit.png' })['17'].inputs.use_tiled_encode, true)
assert.equal(graph['31'].class_type, 'PreviewImage')
const sampling = buildLtxRippleWorkflow({ ...options, previewOverride: { nodeType: 'LTX2SamplingPreviewOverride', fps: 24 } }, models, 'ripple.safetensors', { name: 'source.mp4' }, { name: 'edit.png' })
assert.deepEqual(Array.from(sampling['21'].inputs.model), ['32', 0])
assert.equal(sampling['32'].inputs.preview_rate, 24)
const noPreview = buildLtxRippleWorkflow({ ...options, livePreview: false }, models, 'ripple.safetensors', { name: 'source.mp4' }, { name: 'edit.png' })
assert.equal(noPreview['31'], undefined)
const history = { p: { outputs: { '9': { videos: [{ filename: 'source.mp4', type: 'input' }] }, '29': { videos: [{ filename: 'ripple.mp4', subfolder: 'LTX_Ripple', type: 'output' }] } } } }
assert.equal(extractOutputFile(history, 'p', 'video', '29').filename, 'ripple.mp4')
assert.match(extractOutputUrl(history, 'p', 'http://localhost:8188', 'video', '29'), /ripple.mp4/)
assert.throws(() => buildLtxRippleWorkflow({ ...options, frames: 98 }, models, 'ripple.safetensors', { name: 'source.mp4' }, { name: 'edit.png' }), /supported Ripple frame count/)
console.log('PASS: LTX Ripple frame limits, first-frame guide, LoRA strength, source audio and video output')
