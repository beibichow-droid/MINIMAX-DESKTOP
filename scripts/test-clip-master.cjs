const fs = require('node:fs/promises')
const { readFileSync } = require('node:fs')
const vm = require('node:vm')
const ts = require('typescript')
const path = require('node:path')
const { randomUUID } = require('node:crypto')
const { execFile } = require('node:child_process')
const { promisify } = require('node:util')
const assert = require('node:assert/strict')
const exec = promisify(execFile)
const root = path.resolve('node_modules/.cache/clip-master-validation')
const run = (name, args) => exec(name, args, { windowsHide: true }).then(result => result.stdout)
async function main() {
 await fs.mkdir(root, { recursive: true })
 const source = readFileSync('electron/main.ts', 'utf8')
 const start = source.indexOf("  ipcMain.handle('clip-master:splice'")
 const end = source.indexOf("  ipcMain.handle('video:join'", start)
 let handler
 const context = { ipcMain: { handle: (_, fn) => { handler = fn } }, join: path.join, randomUUID, mkdir: fs.mkdir, writeFile: fs.writeFile, unlink: fs.unlink, app: { getPath: () => root }, resolveVideoSource: async value => value, runFfmpeg: (_, args) => run('ffmpeg', args), runFfprobe: (_, args) => run('ffprobe', args), probeClipVideoMetadata: async input => { const data = JSON.parse(await run('ffprobe', ['-v','error','-show_streams','-of','json',input])); const v = data.streams.find(s => s.codec_type === 'video'); const [n,d] = v.r_frame_rate.split('/').map(Number); return { width:v.width,height:v.height,frameCount:Number(v.nb_frames),fps:n/d,duration:Number(v.duration) } } }
 vm.runInNewContext(ts.transpileModule(source.slice(start,end), {compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText,context)
 const red = path.join(root,'red.mp4'), blue = path.join(root,'blue.mp4')
 await run('ffmpeg',['-v','error','-f','lavfi','-i','color=red:s=64x64:r=24:d=1','-c:v','libx264','-pix_fmt','yuv420p','-y',red])
 await run('ffmpeg',['-v','error','-f','lavfi','-i','color=blue:s=96x64:r=24:d=1','-f','lavfi','-i','sine=frequency=440:duration=1','-c:v','libx264','-pix_fmt','yuv420p','-c:a','aac','-y',blue])
 const before = await fs.readFile(red)
 const result = await handler(null,[{source:red,startFrame:3,endFrame:8},{source:blue,startFrame:10,endFrame:15}],root,'')
 const meta = await context.probeClipVideoMetadata(result.path)
 assert.equal(meta.frameCount,12,'Inclusive exact ranges must produce 12 frames')
 assert.equal(meta.width,64,'Mixed sources normalize to first clip canvas')
 assert.deepEqual(await fs.readFile(red),before,'Source is unchanged')
 const streams = JSON.parse(await run('ffprobe',['-v','error','-show_streams','-of','json',result.path])).streams
 assert.ok(streams.some(s => s.codec_type === 'audio'),'Silent and audio clips share an audio stream')
 await assert.rejects(handler(null,[{source:red,startFrame:20,endFrame:30}],root,''),/Invalid segment/)
 const leftovers = (await fs.readdir(root)).filter(name => name.startsWith('oyama-'))
 assert.equal(leftovers.length,0,'Temporary segments and concat lists are cleaned')
 console.log('PASS: exact inclusive splice, mixed dimensions, silent/audio sources, original preservation, invalid range rejection, temporary cleanup')
}
main().catch(error => { console.error(error); process.exitCode=1 })
